-- =====================================================================
-- V3: compras, transacciones y estados de pago (pagos simulados)
-- =====================================================================

CREATE TABLE orders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT         NOT NULL,
    status     VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    total      NUMERIC(10, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_orders_total CHECK (total >= 0)
);

-- snapshot del precio pagado: no cambia aunque luego cambie el precio del juego
CREATE TABLE order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL,
    game_id    BIGINT         NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT uk_order_items_order_game UNIQUE (order_id, game_id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE RESTRICT,
    CONSTRAINT ck_order_items_price CHECK (unit_price >= 0)
);

CREATE TABLE payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT         NOT NULL,
    amount         NUMERIC(10, 2) NOT NULL,
    method         VARCHAR(30)    NOT NULL,
    status         VARCHAR(20)    NOT NULL DEFAULT 'INITIATED',
    provider_ref   VARCHAR(64)    NOT NULL, -- referencia (UUID) generada por el simulador
    failure_reason VARCHAR(255),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_payments_provider_ref UNIQUE (provider_ref),
    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_payments_status CHECK (status IN ('INITIATED', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0)
);

