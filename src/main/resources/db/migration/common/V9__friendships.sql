-- V9: amistades entre jugadores y visibilidad del perfil.
-- El perfil es privado por defecto: solo lo ven los amigos salvo que su dueño lo haga público.
ALTER TABLE users ADD COLUMN profile_public BOOLEAN DEFAULT FALSE NOT NULL;

-- Una fila por pareja, sea cual sea la dirección: user_low_id es el menor de los dos ids
-- y user_high_id el mayor, así UNIQUE(low, high) evita duplicados cruzados sin índices por expresión.
CREATE TABLE friendships (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT      NOT NULL,
    addressee_id BIGINT      NOT NULL,
    user_low_id  BIGINT      NOT NULL,
    user_high_id BIGINT      NOT NULL,
    status       VARCHAR(10) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    responded_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_friendships_pair UNIQUE (user_low_id, user_high_id),
    CONSTRAINT fk_friendships_requester FOREIGN KEY (requester_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friendships_addressee FOREIGN KEY (addressee_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED')),
    CONSTRAINT ck_friendships_not_self CHECK (requester_id <> addressee_id),
    CONSTRAINT ck_friendships_order CHECK (user_low_id < user_high_id)
);

CREATE INDEX idx_friendships_addressee ON friendships (addressee_id, status);
CREATE INDEX idx_friendships_requester ON friendships (requester_id, status);
