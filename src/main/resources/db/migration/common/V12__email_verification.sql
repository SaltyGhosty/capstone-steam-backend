-- V12: verificación de email. Las cuentas que ya existen quedan verificadas.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN DEFAULT FALSE NOT NULL;
UPDATE users SET email_verified = TRUE;

-- Cada enlace lleva los datos del registro que lo generó (usuario, contraseña, nombre, idioma y tipo de
-- cuenta): al verificar se aplican esos y no los de otro registro posterior con el mismo email.
CREATE TABLE email_verification_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash    VARCHAR(64) NOT NULL,
    expires_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    used_at       TIMESTAMP WITH TIME ZONE,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100),
    locale        VARCHAR(5)   DEFAULT 'es' NOT NULL,
    developer     BOOLEAN      DEFAULT FALSE NOT NULL,
    CONSTRAINT uk_email_verification_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_email_verification_tokens_locale CHECK (locale IN ('es', 'en', 'it'))
);
CREATE INDEX idx_email_verification_tokens_user ON email_verification_tokens (user_id);
