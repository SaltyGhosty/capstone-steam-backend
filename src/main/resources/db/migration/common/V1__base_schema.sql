-- =====================================================================
-- V1: tablas base (usuarios, roles, géneros y juegos)
-- SQL portable entre PostgreSQL y H2 (MODE=PostgreSQL)
-- =====================================================================

CREATE TABLE roles (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    CONSTRAINT uk_roles_name UNIQUE (name)
);

INSERT INTO roles (name) VALUES ('ROLE_USER'), ('ROLE_DEVELOPER'), ('ROLE_ADMIN');

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    email         VARCHAR(255) NOT NULL, -- se guarda normalizado en minúsculas
    password_hash VARCHAR(100) NOT NULL,
    display_name  VARCHAR(100),
    avatar_url    VARCHAR(500),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

CREATE TABLE genres (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL,
    slug VARCHAR(60) NOT NULL,
    CONSTRAINT uk_genres_name UNIQUE (name),
    CONSTRAINT uk_genres_slug UNIQUE (slug)
);

INSERT INTO genres (name, slug) VALUES
    ('Action', 'action'),
    ('Adventure', 'adventure'),
    ('RPG', 'rpg'),
    ('Strategy', 'strategy'),
    ('Simulation', 'simulation'),
    ('Sports', 'sports'),
    ('Racing', 'racing'),
    ('Puzzle', 'puzzle'),
    ('Horror', 'horror'),
    ('Indie', 'indie'),
    ('Shooter', 'shooter'),
    ('Platformer', 'platformer');

CREATE TABLE games (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(150)   NOT NULL,
    slug             VARCHAR(170)   NOT NULL,
    description      VARCHAR(10000),
    developer_id     BIGINT         NOT NULL,
    price            NUMERIC(10, 2) NOT NULL,
    discount_percent INTEGER        NOT NULL DEFAULT 0,
    release_date     DATE,
    cover_url        VARCHAR(500),
    status           VARCHAR(20)    NOT NULL DEFAULT 'DRAFT',
    -- contadores desnormalizados, actualizados con UPDATE atómicos
    sales_count      BIGINT         NOT NULL DEFAULT 0,
    rating_sum       BIGINT         NOT NULL DEFAULT 0,
    rating_count     INTEGER        NOT NULL DEFAULT 0,
    version          BIGINT         NOT NULL DEFAULT 0,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_games_slug UNIQUE (slug),
    CONSTRAINT fk_games_developer FOREIGN KEY (developer_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_games_price CHECK (price >= 0),
    CONSTRAINT ck_games_discount CHECK (discount_percent BETWEEN 0 AND 100),
    CONSTRAINT ck_games_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'DELISTED')),
    CONSTRAINT ck_games_counters CHECK (sales_count >= 0 AND rating_sum >= 0 AND rating_count >= 0)
);

CREATE TABLE game_genres (
    game_id  BIGINT NOT NULL,
    genre_id BIGINT NOT NULL,
    CONSTRAINT pk_game_genres PRIMARY KEY (game_id, genre_id),
    CONSTRAINT fk_game_genres_game FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT fk_game_genres_genre FOREIGN KEY (genre_id) REFERENCES genres (id) ON DELETE CASCADE
);
