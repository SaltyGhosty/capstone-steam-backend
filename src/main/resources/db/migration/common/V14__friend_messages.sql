-- V14: chat uno a uno entre amigos.
-- user_low_id/user_high_id son la pareja ordenada (como en friendships) para leer una conversación con un índice.
-- Los mensajes no dependen de la fila de friendships: al dejar de ser amigos la conversación queda guardada.
CREATE TABLE friend_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id    BIGINT        NOT NULL,
    recipient_id BIGINT        NOT NULL,
    user_low_id  BIGINT        NOT NULL,
    user_high_id BIGINT        NOT NULL,
    body         VARCHAR(1000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    read_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_friend_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_friend_messages_recipient FOREIGN KEY (recipient_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_friend_messages_body CHECK (length(body) > 0),
    CONSTRAINT ck_friend_messages_pair CHECK (
        (user_low_id = sender_id AND user_high_id = recipient_id)
        OR (user_low_id = recipient_id AND user_high_id = sender_id)
    )
);

CREATE INDEX idx_friend_messages_pair ON friend_messages (user_low_id, user_high_id, created_at);
CREATE INDEX idx_friend_messages_unread ON friend_messages (recipient_id, read_at);
